/**
 * A command line the CLI cannot act on: an unknown option, a missing value, conflicting options, an unreadable password
 * or key file. Reported on stderr with a pointer to {@code --help}, exit code 64.
 */
final class CliUsageException extends Exception {

	private static final long serialVersionUID = 1L;

	CliUsageException(String message) {
		super(message);
	}

	CliUsageException(String message, Throwable cause) {
		super(message, cause);
	}
}
